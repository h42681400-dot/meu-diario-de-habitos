-- Cottontail • registro de aceite das versões legais
-- Revisar e executar no SQL Editor do Supabase após backup.
-- Não altera tabelas existentes do app. Cria apenas uma tabela e um trigger dedicados.

create table if not exists public.legal_acceptances (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  terms_version text not null,
  privacy_version text not null,
  community_version text not null,
  accepted_at timestamptz not null,
  created_at timestamptz not null default now()
);

alter table public.legal_acceptances enable row level security;

drop policy if exists "Usuário pode consultar seus aceites" on public.legal_acceptances;
create policy "Usuário pode consultar seus aceites"
on public.legal_acceptances for select
to authenticated
using (auth.uid() = user_id);

-- Não criar policy de INSERT para o cliente: o trigger abaixo registra o aceite
-- diretamente no momento em que o Supabase Auth cria a conta.
create or replace function public.cottontail_log_legal_acceptance()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  metadata jsonb;
begin
  metadata := coalesce(new.raw_user_meta_data, '{}'::jsonb);

  if metadata ? 'cottontail_legal_accepted_at'
     and metadata ? 'cottontail_terms_version'
     and metadata ? 'cottontail_privacy_version'
     and metadata ? 'cottontail_community_version' then
    insert into public.legal_acceptances (
      user_id, terms_version, privacy_version, community_version, accepted_at
    ) values (
      new.id,
      metadata ->> 'cottontail_terms_version',
      metadata ->> 'cottontail_privacy_version',
      metadata ->> 'cottontail_community_version',
      (metadata ->> 'cottontail_legal_accepted_at')::timestamptz
    );
  end if;
  return new;
end;
$$;

drop trigger if exists cottontail_auth_legal_acceptance on auth.users;
create trigger cottontail_auth_legal_acceptance
after insert on auth.users
for each row execute function public.cottontail_log_legal_acceptance();

