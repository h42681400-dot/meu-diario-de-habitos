-- Cottontail • registro de aceites legais e confirmação provisória de maioridade
-- Execute no SQL Editor do Supabase. Faça backup antes.
-- Esta migração cria somente tabelas e triggers dedicados; não altera tabelas sociais existentes.

create table if not exists public.legal_acceptances (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  terms_version text not null,
  privacy_version text not null,
  community_version text not null,
  accepted_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

alter table public.legal_acceptances enable row level security;
drop policy if exists "Usuário pode consultar seus aceites" on public.legal_acceptances;
create policy "Usuário pode consultar seus aceites"
on public.legal_acceptances for select to authenticated
using (auth.uid() = user_id);

create table if not exists public.beta_age_attestations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  attested_at timestamptz not null default now(),
  method text not null default 'self_declaration'
);
alter table public.beta_age_attestations enable row level security;
drop policy if exists "Usuário pode consultar sua confirmação de idade" on public.beta_age_attestations;
create policy "Usuário pode consultar sua confirmação de idade"
on public.beta_age_attestations for select to authenticated
using (auth.uid() = user_id);

-- O trigger usa horário do servidor, não o horário informado pelo navegador.
create or replace function public.cottontail_log_auth_declarations()
returns trigger language plpgsql security definer set search_path = '' as $$
declare metadata jsonb;
begin
  metadata := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  if metadata ? 'cottontail_terms_version'
     and metadata ? 'cottontail_privacy_version'
     and metadata ? 'cottontail_community_version' then
    insert into public.legal_acceptances (user_id, terms_version, privacy_version, community_version, accepted_at)
    values (new.id, metadata ->> 'cottontail_terms_version', metadata ->> 'cottontail_privacy_version', metadata ->> 'cottontail_community_version', now());
  end if;
  if metadata ->> 'cottontail_beta_adult_attested' = 'true' then
    insert into public.beta_age_attestations (user_id, attested_at, method)
    values (new.id, now(), 'self_declaration');
  end if;
  return new;
end;
$$;

drop trigger if exists cottontail_auth_legal_acceptance on auth.users;
create trigger cottontail_auth_legal_acceptance
after insert on auth.users for each row
execute function public.cottontail_log_auth_declarations();

-- Registra também a confirmação feita por contas já existentes ao entrar novamente.
create or replace function public.cottontail_log_age_attestation_update()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if coalesce(new.raw_user_meta_data ->> 'cottontail_beta_adult_attested','false') = 'true'
     and coalesce(old.raw_user_meta_data ->> 'cottontail_beta_adult_attested','false') <> 'true' then
    insert into public.beta_age_attestations (user_id, attested_at, method)
    values (new.id, now(), 'self_declaration');
  end if;
  return new;
end;
$$;
drop trigger if exists cottontail_auth_age_attestation_update on auth.users;
create trigger cottontail_auth_age_attestation_update
after update of raw_user_meta_data on auth.users for each row
execute function public.cottontail_log_age_attestation_update();

